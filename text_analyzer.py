# Анализатор текста — мой первый кейс для портфолио

def анализировать_текст(текст):
    """Анализирует текст и возвращает статистику"""
    
    # Разбиваем текст на слова
    слова = текст.split()
    
    # Считаем символы
    символов = len(текст)
    
    # Считаем предложения (по точкам)
    предложений = текст.count(".") + текст.count("!") + текст.count("?")
    
    # Находим самое длинное слово
    самое_длинное = max(слова, key=len)
    
    # Результат
    print("=== АНАЛИЗ ТЕКСТА ===")
    print("Количество слов:", len(слова))
    print("Количество символов:", символов)
    print("Количество предложений:", предложений)
    print("Самое длинное слово:", самое_длинное)
    print("Средняя длина слова:", round(символов / len(слова), 1))

# Наш текст для анализа
текст = "Python это отличный язык для искусственного интеллекта. Он простой и мощный. Я учусь программировать каждый день!"

# Запускаем анализ
анализировать_текст(текст)